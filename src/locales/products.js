export const getLocalizedProductName = (product, lang = "fr") => {
  if (!product) return "";
  if (lang !== "en") return product.name || "";

  // Check if id contains size (e.g. "1-M" or "25-XL")
  let baseId = null;
  let sizeSuffix = "";
  if (product.id != null) {
    const idStr = String(product.id);
    const parts = idStr.split("-");
    if (parts.length === 2 && !isNaN(Number(parts[0]))) {
      baseId = Number(parts[0]);
      sizeSuffix = ` — ${parts[1]}`;
    } else if (!isNaN(Number(idStr))) {
      baseId = Number(idStr);
    }
  }

  // Also check if name has " — SIZE" suffix
  let rawName = product.name || "";
  if (!sizeSuffix && rawName.includes(" — ")) {
    const nameParts = rawName.split(" — ");
    if (nameParts.length >= 2) {
      rawName = nameParts[0];
      sizeSuffix = ` — ${nameParts.slice(1).join(" — ")}`;
    }
  }

  if (baseId && PRODUCT_TRANSLATIONS_EN_BY_ID[baseId]) {
    return PRODUCT_TRANSLATIONS_EN_BY_ID[baseId] + sizeSuffix;
  }

  if (rawName && PRODUCT_TRANSLATIONS_EN_BY_NAME[rawName]) {
    return PRODUCT_TRANSLATIONS_EN_BY_NAME[rawName] + sizeSuffix;
  }

  return product.name || "";
};
